        (500, 220, 150, 50, "Redis Cache",    "queues · pubsub",         RED,  "warn"),
        (740, 220, 200, 50, "ClickHouse",     "analytics · 1B rows",    GRN,  "ok"),
        (500, 300, 150, 50, "RabbitMQ",       "generation jobs",        YEL,  "ok"),
